#!/usr/bin/env python3
"""
Review pseudo masks (generated by SCTransNet) for IR small/dim target datasets.

Every image is reviewed manually (no automatic acceptance).
Matplotlib window, no terminal input:
    M          = mask is correct   -> refined_dataset/correct_images
    R          = mask rejected     -> refined_dataset/manual_annotation
    LEFT ARROW = undo previous decision and show that image again
    Q / Esc    = quit (progress is saved, re-run to resume)

Expected layout (NUDT-SIRST style):
    dataset/custom_data/images/*.png
    dataset/custom_data/masks/*.png     (pseudo masks)

Usage:
    python review_pseudo_masks.py
    python review_pseudo_masks.py --dataset dataset/custom_data --out refined_dataset
"""
import argparse
import csv
import json
import logging
import shutil
import sys
from datetime import datetime
from pathlib import Path

import cv2
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.figure import Figure

IMG_EXTS = {".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"}

# action code -> (group directory, label)
ACTIONS = {
    "M": ("correct_images", "mask_correct"),
    "R": ("manual_annotation", "mask_rejected"),
}
GROUPS = ("correct_images", "manual_annotation")
SUBDIRS = ("images", "mask", "visualization")

log = logging.getLogger("review")


# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------
def build_index(directory):
    files = {}
    for p in sorted(Path(directory).iterdir()):
        if p.is_file() and p.suffix.lower() in IMG_EXTS:
            if p.stem in files:
                raise ValueError(f"Duplicate filename stem '{p.stem}' in {directory}.")
            files[p.stem] = p
    return files


def read_raw(path):
    img = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if img is None:
        raise IOError(f"Cannot read image {path}")
    return img


def raw_for_display(img):
    if img.ndim == 3:
        img = cv2.cvtColor(img[:, :, :3], cv2.COLOR_BGR2RGB)
    if img.dtype != np.uint8:
        img = img.astype(np.float32)
        img = (255 * (img - img.min()) / max(img.max() - img.min(), 1e-6)).astype(np.uint8)
    return img


def read_binary_mask(path, shape):
    """Return (uint8 0/255 mask, shape_mismatch). Missing/unreadable mask -> empty mask."""
    if path is None:
        return np.zeros(shape, np.uint8), False
    m = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
    if m is None:
        log.warning("Cannot read mask %s -> treating as empty", path)
        return np.zeros(shape, np.uint8), False
    mismatch = m.shape != shape
    if mismatch:
        log.warning("Shape mismatch for %s (mask %s vs image %s)", path.name, m.shape, shape)
        m = cv2.resize(m, (shape[1], shape[0]), interpolation=cv2.INTER_NEAREST)
    thr = 0 if m.max() <= 1 else 127  # supports 0/1 and 0/255 masks
    return ((m > thr).astype(np.uint8)) * 255, mismatch


def count_targets(mask):
    n, _ = cv2.connectedComponents((mask > 0).astype(np.uint8), connectivity=8)
    return n - 1


def overlay(raw, mask):
    """Raw image with mask contours in red (visible even for tiny targets)."""
    rgb = raw_for_display(raw)
    if rgb.ndim == 2:
        rgb = cv2.cvtColor(rgb, cv2.COLOR_GRAY2RGB)
    rgb = rgb.copy()
    cnts, _ = cv2.findContours((mask > 0).astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    cv2.drawContours(rgb, cnts, -1, (255, 0, 0), 1)
    return rgb


def draw_panels(axes, raw, mask, n_targets):
    for ax in axes:
        ax.clear()
        ax.axis("off")
    axes[0].imshow(raw_for_display(raw), cmap="gray")
    axes[0].set_title("Raw image")
    axes[1].imshow(mask, cmap="gray", vmin=0, vmax=255)
    axes[1].set_title(f"Pseudo mask ({n_targets} target(s))")
    axes[2].imshow(overlay(raw, mask))
    axes[2].set_title("Overlay (red = mask contour)")


def save_visualization(path, raw, mask, n_targets, title):
    fig = Figure(figsize=(15, 5.5))
    axes = fig.subplots(1, 3)
    draw_panels(axes, raw, mask, n_targets)
    fig.suptitle(title, fontsize=11)
    fig.savefig(str(path), dpi=100, bbox_inches="tight")


# ----------------------------------------------------------------------------
# Output manager
# ----------------------------------------------------------------------------
class Store:
    def __init__(self, out_dir):
        self.out = Path(out_dir)
        for g in GROUPS:
            for s in SUBDIRS:
                (self.out / g / s).mkdir(parents=True, exist_ok=True)
        self.state_file = self.out / "state.json"
        self.state = json.loads(self.state_file.read_text()) if self.state_file.exists() else {}

    def _save_state(self):
        tmp = self.state_file.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.state, indent=1))
        tmp.replace(self.state_file)

    def save(self, item, action, raw, mask):
        group, label = ACTIONS[action]
        name, stem = item["img"].name, item["img"].stem
        base = self.out / group
        shutil.copy2(item["img"], base / "images" / name)
        cv2.imwrite(str(base / "mask" / f"{stem}.png"), mask)  # pseudo mask (final GT / starting point)
        title = f"{name}   ->   {label.upper()}"
        save_visualization(base / "visualization" / f"{stem}.png", raw, mask, item["n_targets"], title)
        self.state[name] = {"action": action, "time": datetime.now().isoformat(timespec="seconds")}
        self._save_state()
        self.write_lists()
        return base

    def undo(self, item):
        name, stem = item["img"].name, item["img"].stem
        for g in GROUPS:
            for sub, fname in (("images", name), ("mask", f"{stem}.png"),
                               ("visualization", f"{stem}.png")):
                f = self.out / g / sub / fname
                if f.exists():
                    f.unlink()
        self.state.pop(name, None)
        self._save_state()
        self.write_lists()

    def write_lists(self):
        header = ["image", "action", "time"]
        rows = {g: [] for g in GROUPS}
        for name, st in sorted(self.state.items()):
            g, label = ACTIONS[st["action"]]
            rows[g].append([name, label, st["time"]])
        for g, fname in (("correct_images", "correct_images_list.csv"),
                         ("manual_annotation", "manual_annotation_list.csv")):
            with open(self.out / g / fname, "w", newline="") as f:
                w = csv.writer(f)
                w.writerow(header)
                w.writerows(rows[g])
        (self.out / "correct_images" / "correct_images_list.txt").write_text(
            "".join(r[0] + "\n" for r in rows["correct_images"]))
        with open(self.out / "all_decisions.csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(header + ["group"])
            for g in GROUPS:
                for r in rows[g]:
                    w.writerow(r + [g])


# ----------------------------------------------------------------------------
# Interactive reviewer
# ----------------------------------------------------------------------------
class Reviewer:
    def __init__(self, queue, items, store):
        self.queue, self.items, self.store = queue, items, store
        self.idx = next((i for i, n in enumerate(queue) if n not in store.state), len(queue))
        for k in [k for k in plt.rcParams if k.startswith("keymap.")]:
            plt.rcParams[k] = []  # disable default matplotlib shortcuts
        self.fig, self.axes = plt.subplots(1, 3, figsize=(15, 6.5))
        self.fig.canvas.manager.set_window_title("Pseudo mask review")
        self.title = self.fig.suptitle("", fontsize=11)
        self.fig.text(0.5, 0.02,
                      "M = Mask correct    R = Reject (manual annotation)    "
                      "<- (left arrow) = Undo previous    Q = Quit",
                      ha="center", fontsize=12, weight="bold")
        self.fig.canvas.mpl_connect("key_press_event", self.on_key)
        self.fig.canvas.mpl_connect("close_event", self.on_close)
        self.show()

    def load(self, item):
        raw = read_raw(item["img"])
        mask, _ = read_binary_mask(item["mask"], raw.shape[:2])
        return raw, mask

    def show(self):
        n = len(self.queue)
        if self.idx >= n:
            for ax in self.axes:
                ax.clear()
                ax.axis("off")
            self.axes[1].text(0.5, 0.5, "All images reviewed!\n\nPress <- to undo the last one\nor Q to quit",
                              ha="center", va="center", fontsize=16, transform=self.axes[1].transAxes)
            self.title.set_text(f"Done: {n}/{n} reviewed")
            log.info("All %d images reviewed. Press LEFT to undo or Q to quit.", n)
        else:
            name = self.queue[self.idx]
            item = self.items[name]
            raw, mask = self.load(item)
            draw_panels(self.axes, raw, mask, item["n_targets"])
            flag = f"   |   FLAGGED: {', '.join(item['flags'])}" if item["flags"] else ""
            self.title.set_text(f"[{self.idx + 1}/{n}]  {name}   {raw.shape[1]}x{raw.shape[0]}{flag}")
            log.info("Showing [%d/%d] %s  targets=%d%s", self.idx + 1, n, name, item["n_targets"], flag)
        self.fig.canvas.draw_idle()

    def on_key(self, event):
        key = (event.key or "").lower()
        if key in ("q", "escape"):
            plt.close(self.fig)
            return
        if key == "left":
            if self.idx == 0:
                log.info("Already at the first image, nothing to undo.")
                return
            self.idx -= 1
            name = self.queue[self.idx]
            prev = self.store.state.get(name, {}).get("action", "none")
            self.store.undo(self.items[name])
            log.info("UNDO %s (was '%s'); files removed from refined dataset", name, prev)
            self.show()
            return
        if key in ("m", "r") and self.idx < len(self.queue):
            action = key.upper()
            name = self.queue[self.idx]
            item = self.items[name]
            try:
                raw, mask = self.load(item)
                base = self.store.save(item, action, raw, mask)
            except Exception as e:  # stay on the same image
                log.error("Failed to save %s: %s", name, e)
                return
            log.info("[%d/%d] %s -> %s saved to %s", self.idx + 1, len(self.queue), name,
                     ACTIONS[action][1].upper(), base)
            self.idx += 1
            self.show()

    def on_close(self, _):
        done = sum(1 for n in self.queue if n in self.store.state)
        log.info("Window closed. Reviewed %d/%d. Re-run the script to resume.", done, len(self.queue))


# ----------------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--dataset", default="dataset/custom_data")
    ap.add_argument("--images-dir", default="images")
    ap.add_argument("--masks-dir", default="masks")
    ap.add_argument("--out", default="refined_dataset")
    ap.add_argument("--order", choices=["name", "targets"], default="name",
                    help="review order: by filename, or by number of targets in the mask (ascending)")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s",
                        handlers=[logging.StreamHandler(sys.stdout),
                                  logging.FileHandler(out / "review.log", encoding="utf-8")])

    ds = Path(args.dataset)
    img_idx = build_index(ds / args.images_dir)
    mask_idx = build_index(ds / args.masks_dir)
    log.info("Found %d images, %d masks", len(img_idx), len(mask_idx))

    store = Store(out)
    items = {}
    for stem, img_path in img_idx.items():
        mask_path = mask_idx.get(stem)
        flags = []
        try:
            raw = read_raw(img_path)
            mask, bad = read_binary_mask(mask_path, raw.shape[:2])
        except Exception as e:
            log.error("Skipping %s: %s", img_path.name, e)
            continue
        if mask_path is None:
            flags.append("mask missing")
        if bad:
            flags.append("shape mismatch")
        n_t = count_targets(mask)
        if mask_path is not None and n_t == 0:
            flags.append("empty mask")
        items[img_path.name] = {"img": img_path, "mask": mask_path, "n_targets": n_t, "flags": flags}

    queue = list(items)
    if args.order == "targets":
        queue.sort(key=lambda n: (items[n]["n_targets"], n))
    done = sum(1 for n in queue if n in store.state)
    log.info("Total: %d | already reviewed: %d | remaining: %d", len(queue), done, len(queue) - done)

    if not queue:
        log.info("Nothing to review.")
        return
    Reviewer(queue, items, store)
    plt.show()
    log.info("Finished. Decisions: %s", out / "all_decisions.csv")


if __name__ == "__main__":
    main()
